#!/bin/bash
set -e
VERSION=1.5.7
ROOT=$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)
OUT=${XNU_SRC:-$ROOT/xnu-src/xnu-8796.121.2}/bsd/miscfs/packfs/zstddeclib.c
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
curl -sL --fail -o "$TMP/zstd.tar.gz" https://github.com/facebook/zstd/releases/download/v$VERSION/zstd-$VERSION.tar.gz
tar xzf "$TMP/zstd.tar.gz" -C "$TMP"
(cd "$TMP/zstd-$VERSION/build/single_file_libs" && ./create_single_file_decoder.sh > /dev/null 2>&1)
{
	echo "/*"
	echo " * Zstandard $VERSION, decoder only: generated by tools/mk-zstddec.sh (build/single_file_libs/"
	echo " * create_single_file_decoder.sh of the Zstandard distribution). Not to be edited by hand."
	echo " * Zstandard is Copyright (c) Meta Platforms, Inc. and affiliates, under the BSD licence (or GPLv2)."
	echo " */"
	sed 's|^#include <limits.h>|#include <machine/limits.h>|' "$TMP/zstd-$VERSION/build/single_file_libs/zstddeclib.c"
} > "$OUT"
echo "mk-zstddec.sh: $OUT ($(wc -c < "$OUT") bytes)"
