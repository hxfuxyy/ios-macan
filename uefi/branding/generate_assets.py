#!/usr/bin/env python3

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib,json
here=Path(__file__).resolve().parent
out=here.parent/'mu/Platforms/OnePlus/macanPkg/Applications/DarwinMenu/HackIOSAssets.h'
def array(name,data):
 return 'static const unsigned char '+name+'[] = {\n'+ '\n'.join(','.join(str(x) for x in data[i:i+32])+',' for i in range(0,len(data),32))+'\n};\n'
s='/* Generated by hackios/generate_assets.py. Noto Sans: SIL Open Font License. */\n'
logo=Image.open(here/'assets/logo.png').convert('L').resize((160,160),Image.Resampling.LANCZOS)
s+=array('hx_logo',logo.tobytes())
for name,size,weight in [('title',32,'Medium'),('body',20,'Medium'),('small',14,'Regular'),('caption',12,'Regular')]:
 fontfile=Path('/usr/share/fonts/noto')/f'NotoSans-{weight}.ttf'
 font=ImageFont.truetype(str(fontfile),size)
 height=size+12; widths=[]; data=bytearray();offsets=[]
 for c in range(32,127):
  width=int(font.getlength(chr(c))+1); widths.append(width);offsets.append(len(data))
  im=Image.new('L',(width,height));ImageDraw.Draw(im).text((0,0),chr(c),font=font,fill=255)
  data.extend(im.tobytes())
 s+=f'static const int hx_{name}_height={height};\n'
 s+='static const unsigned int hx_'+name+'_offset[] = {'+','.join(map(str,offsets))+'};\n'
 s+=array('hx_'+name+'_width',widths)+array('hx_'+name+'_data',data)
 s+=f'static const HxFont hx_{name} = {{hx_{name}_data,hx_{name}_width,hx_{name}_offset,{height}}};\n'
out.write_text(s)
print(out, out.stat().st_size)
