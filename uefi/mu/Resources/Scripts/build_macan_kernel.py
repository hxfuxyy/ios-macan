#!/usr/bin/env python3
"""Build the pinned Ace 6T GKI baseline with a 4 GiB free-space guard."""
import argparse
import hashlib
import json
import os
import runpy
import signal
import shutil
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESERVE = 4 * 1024**3


def run(command, cwd, env):
    print("RUN", " ".join(map(str, command)), flush=True)
    process = subprocess.Popen(list(map(str, command)), cwd=cwd, env=env, start_new_session=True)
    try:
        while process.poll() is None:
            if shutil.disk_usage(cwd).free < RESERVE:
                raise RuntimeError("Build stopped: fewer than 4 GiB free")
            time.sleep(2)
        if process.returncode:
            raise subprocess.CalledProcessError(process.returncode, command)
    finally:
        if process.poll() is None:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--jobs", type=int, default=6)
    parser.add_argument("--configure-only", action="store_true")
    args = parser.parse_args()
    if not 1 <= args.jobs <= 16:
        parser.error("jobs must be between 1 and 16")
    workspace = args.workspace.resolve()
    for name in ["common", "clang", "rust", "bindgen"]:
        if not (workspace / f"{name}.source.json").is_file():
            raise RuntimeError(f"Input not completely prepared: {name}")
    source = workspace / "common"
    # Reproduce the list generated by common/BUILD.bazel. Keep protection
    # enabled; the plain Make build otherwise lacks this generated input.
    definitions = runpy.run_path(str(source / "modules.bzl"))
    protected = definitions["get_gki_protected_modules_list"]("arm64")
    (source / "protected_module_names_list").write_text(
        "\n".join(name.removesuffix(".ko") for name in protected) + "\n")
    host_patch = ROOT / "Resources/LinuxRamTest/kernel-host-libbpf.patch"
    marker = workspace / "host-libbpf-patch.sha256"
    patch_hash = hashlib.sha256(host_patch.read_bytes()).hexdigest()
    if marker.exists():
        if marker.read_text().strip() != patch_hash:
            raise RuntimeError("Host patch changed; inspect existing source first")
    else:
        run(["patch", "--batch", "--forward", "-p1", "-i", host_patch], source, os.environ.copy())
        marker.write_text(patch_hash + "\n")
    output = workspace / "out"
    output.mkdir(exist_ok=True)
    stock_config = ROOT / "artifacts/ace6t/kernel.config"
    if not (output / ".config").exists():
        shutil.copyfile(stock_config, output / ".config")
        # Keep the stock hardware/CFI/DWARF configuration. Export all symbols
        # for development; absent build-system-generated allowlists cannot
        # safely be guessed. This does not bypass module CRC verification.
        run([source / "scripts/config", "--file", output / ".config",
             "--disable", "TRIM_UNUSED_KSYMS", "--set-str", "UNUSED_KSYMS_WHITELIST", "",
             "--set-str", "LOCALVERSION", "-android16-5-ace6t-linux-4k",
             "--disable", "LOCALVERSION_AUTO"], source, os.environ.copy())
    env = os.environ.copy()
    env["PATH"] = ":".join([str(workspace / "clang/bin"), str(workspace / "rust/bin"),
                              str(workspace / "bindgen"), env["PATH"]])
    env["LIBCLANG_PATH"] = str(workspace / "clang/lib")
    env["KBUILD_GENDWARFKSYMS_STABLE"] = "1"
    env["KBUILD_BUILD_USER"] = "ace6t"
    env["KBUILD_BUILD_HOST"] = "linux-bringup"
    env["KBUILD_BUILD_TIMESTAMP"] = "Fri Dec 5 02:15:49 UTC 2025"
    make = ["make", "-C", source, f"O={output}", "ARCH=arm64", "LLVM=1",
            "HOSTCFLAGS=-O2 -std=gnu11",
            "KCFLAGS=-D__ANDROID_COMMON_KERNEL__"]
    run(make + ["olddefconfig"], workspace, env)
    with (output / "config.diff").open("w") as file:
        subprocess.run([source / "scripts/diffconfig", stock_config, output / ".config"],
                       stdout=file, check=True, env=env)
    if args.configure_only:
        return
    run(make + [f"-j{args.jobs}", "Image"], workspace, env)
    # Image builds vmlinux.symvers, sufficient for external module MODPOST.
    symvers = output / "vmlinux.symvers"
    if not symvers.is_file():
        raise RuntimeError("Kernel symbol versions missing")
    shutil.copyfile(symvers, output / "Module.symvers")
    files = {}
    for name in ["arch/arm64/boot/Image", "vmlinux", "Module.symvers", ".config", "config.diff"]:
        path = output / name
        digest = hashlib.sha256()
        with path.open("rb") as file:
            for chunk in iter(lambda: file.read(1024 * 1024), b""):
                digest.update(chunk)
        files[name] = {"bytes": path.stat().st_size, "sha256": digest.hexdigest()}
    (workspace / "kernel-build.json").write_text(json.dumps({
        "files": files, "free_bytes": shutil.disk_usage(workspace).free,
        "host_libbpf_patch_sha256": patch_hash,
        "phone_booted": False, "stock_module_compatibility": "pending",
    }, indent=2) + "\n")
    print("Kernel Image built. Module compatibility and phone boot remain unverified.", flush=True)


if __name__ == "__main__":
    main()
